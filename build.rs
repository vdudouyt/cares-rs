use std::env;
use std::path::PathBuf;

/// Legacy accessors from upstream `<ares_dns.h>`.  Consumers such as Xymon's
/// `dns2.c` use these macros directly; they are not part of the generated
/// `<ares.h>`.
const ARES_DNS_COMPAT: &str = r#"
#define DNS__16BIT(p)                                                \
  ((unsigned short)((unsigned int)0xffff &                           \
                    (((unsigned int)((unsigned char)(p)[0]) << 8U) | \
                     ((unsigned int)((unsigned char)(p)[1])))))

#define DNS__32BIT(p)                                              \
  ((unsigned int)(((unsigned int)((unsigned char)(p)[0]) << 24U) | \
                  ((unsigned int)((unsigned char)(p)[1]) << 16U) | \
                  ((unsigned int)((unsigned char)(p)[2]) << 8U) |  \
                  ((unsigned int)((unsigned char)(p)[3]))))

#define DNS__SET16BIT(p, v)                       \
  (((p)[0] = (unsigned char)(((v) >> 8) & 0xff)), \
   ((p)[1] = (unsigned char)((v) & 0xff)))
#define DNS__SET32BIT(p, v)                        \
  (((p)[0] = (unsigned char)(((v) >> 24) & 0xff)), \
   ((p)[1] = (unsigned char)(((v) >> 16) & 0xff)), \
   ((p)[2] = (unsigned char)(((v) >> 8) & 0xff)),  \
   ((p)[3] = (unsigned char)((v) & 0xff)))

#define DNS_HEADER_QID(h)     DNS__16BIT(h)
#define DNS_HEADER_QR(h)      (((h)[2] >> 7) & 0x1)
#define DNS_HEADER_OPCODE(h)  (((h)[2] >> 3) & 0xf)
#define DNS_HEADER_AA(h)      (((h)[2] >> 2) & 0x1)
#define DNS_HEADER_TC(h)      (((h)[2] >> 1) & 0x1)
#define DNS_HEADER_RD(h)      ((h)[2] & 0x1)
#define DNS_HEADER_RA(h)      (((h)[3] >> 7) & 0x1)
#define DNS_HEADER_Z(h)       (((h)[3] >> 4) & 0x7)
#define DNS_HEADER_RCODE(h)   ((h)[3] & 0xf)
#define DNS_HEADER_QDCOUNT(h) DNS__16BIT((h) + 4)
#define DNS_HEADER_ANCOUNT(h) DNS__16BIT((h) + 6)
#define DNS_HEADER_NSCOUNT(h) DNS__16BIT((h) + 8)
#define DNS_HEADER_ARCOUNT(h) DNS__16BIT((h) + 10)

#define DNS_HEADER_SET_QID(h, v) DNS__SET16BIT(h, v)
#define DNS_HEADER_SET_QR(h, v)  ((h)[2] |= (unsigned char)(((v) & 0x1) << 7))
#define DNS_HEADER_SET_OPCODE(h, v) \
  ((h)[2] |= (unsigned char)(((v) & 0xf) << 3))
#define DNS_HEADER_SET_AA(h, v)      ((h)[2] |= (unsigned char)(((v) & 0x1) << 2))
#define DNS_HEADER_SET_TC(h, v)      ((h)[2] |= (unsigned char)(((v) & 0x1) << 1))
#define DNS_HEADER_SET_RD(h, v)      ((h)[2] |= (unsigned char)((v) & 0x1))
#define DNS_HEADER_SET_RA(h, v)      ((h)[3] |= (unsigned char)(((v) & 0x1) << 7))
#define DNS_HEADER_SET_Z(h, v)       ((h)[3] |= (unsigned char)(((v) & 0x7) << 4))
#define DNS_HEADER_SET_RCODE(h, v)   ((h)[3] |= (unsigned char)((v) & 0xf))
#define DNS_HEADER_SET_QDCOUNT(h, v) DNS__SET16BIT((h) + 4, v)
#define DNS_HEADER_SET_ANCOUNT(h, v) DNS__SET16BIT((h) + 6, v)
#define DNS_HEADER_SET_NSCOUNT(h, v) DNS__SET16BIT((h) + 8, v)
#define DNS_HEADER_SET_ARCOUNT(h, v) DNS__SET16BIT((h) + 10, v)

#define DNS_QUESTION_TYPE(q)  DNS__16BIT(q)
#define DNS_QUESTION_CLASS(q) DNS__16BIT((q) + 2)
#define DNS_QUESTION_SET_TYPE(q, v)  DNS__SET16BIT(q, v)
#define DNS_QUESTION_SET_CLASS(q, v) DNS__SET16BIT((q) + 2, v)

#define DNS_RR_TYPE(r)  DNS__16BIT(r)
#define DNS_RR_CLASS(r) DNS__16BIT((r) + 2)
#define DNS_RR_TTL(r)   DNS__32BIT((r) + 4)
#define DNS_RR_LEN(r)   DNS__16BIT((r) + 8)

#define DNS_RR_SET_TYPE(r, v)  DNS__SET16BIT(r, v)
#define DNS_RR_SET_CLASS(r, v) DNS__SET16BIT((r) + 2, v)
#define DNS_RR_SET_TTL(r, v)   DNS__SET32BIT((r) + 4, v)
#define DNS_RR_SET_LEN(r, v)   DNS__SET16BIT((r) + 8, v)
"#;

const ARES_VERSION_HEADER: &str = r#"/* Generated by cares-rs. */
#ifndef ARES__VERSION_H
#define ARES__VERSION_H

/* This is the global package copyright */
#define ARES_COPYRIGHT "2004 - 2025 Daniel Stenberg, <daniel@haxx.se>."

#define ARES_VERSION_MAJOR 1
#define ARES_VERSION_MINOR 34
#define ARES_VERSION_PATCH 6
#define ARES_VERSION_STR "1.34.6"

/* NOTE: We cannot make the version string a C preprocessor stringify operation
 *       due to assumptions made by integrators that aren't properly using
 *       pkgconf or cmake and are doing their own detection based on parsing
 *       this header */

#define ARES_VERSION                                        \
  ((ARES_VERSION_MAJOR << 16) | (ARES_VERSION_MINOR << 8) | \
   (ARES_VERSION_PATCH))

#endif
"#;

// Generate include/ares.h with cbindgen on every build so it can't drift from
// the .so; the header is a git-ignored build artifact.
fn main() {
    let crate_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());

    println!("cargo:rerun-if-changed=src/ffi");
    // cbindgen parses the whole crate; core defines types the ffi signatures reference.
    println!("cargo:rerun-if-changed=src/core");
    println!("cargo:rerun-if-changed=cbindgen.toml");
    println!("cargo:rerun-if-changed=build.rs");
    // Watch the output so deletion/tampering re-triggers generation; cbindgen only
    // rewrites on content change, so an unchanged regen doesn't cause a rebuild loop.
    println!("cargo:rerun-if-changed=include/ares.h");

    let config = cbindgen::Config::from_file(crate_dir.join("cbindgen.toml"))
        .expect("read cbindgen.toml");

    let bindings = match cbindgen::Builder::new()
        .with_crate(&crate_dir)
        .with_config(config)
        .generate()
    {
        Ok(b) => b,
        // Warn instead of failing the build if header generation hiccups.
        Err(e) => {
            println!("cargo:warning=cbindgen header generation failed: {e}");
            return;
        }
    };

    // include/ is git-ignored; create it for fresh checkouts (write_to_file only
    // rewrites when contents change, so mtimes stay untouched).
    let include_dir = crate_dir.join("include");
    let _ = std::fs::create_dir_all(&include_dir);
    bindings.write_to_file(include_dir.join("ares.h"));

    // Upstream splits its public header into ares_version.h, ares_build.h,
    // ares_dns.h, ares_dns_record.h and ares_nameser.h. Our generated ares.h is
    // self-contained, so provide include-compatible stubs for consumers that
    // include one of the split headers directly.
    for (name, guard) in [
        ("ares_version.h", "ARES__VERSION_H"),
        ("ares_build.h", "__CARES_BUILD_H"),
        ("ares_dns.h", "HEADER_CARES_DNS_H"),
        ("ares_dns_record.h", "__ARES_DNS_RECORD_H"),
        ("ares_nameser.h", "ARES_NAMESER_H"),
    ] {
        let body = if name == "ares_version.h" {
            ARES_VERSION_HEADER.to_string()
        } else if name == "ares_dns.h" {
            format!(
                "/* Generated by cares-rs: public API in <ares.h>; legacy DNS macros below. */\n\
                 #ifndef {guard}\n\
                 #define {guard}\n\
                 #include <ares.h>\n\
                 {ARES_DNS_COMPAT}\n\
                 #endif\n"
            )
        } else {
            format!(
                "/* Generated by cares-rs: the public API is in <ares.h>. */\n\
                 #ifndef {guard}\n\
                 #define {guard}\n\
                 #include <ares.h>\n\
                 #endif\n"
            )
        };
        let _ = std::fs::write(include_dir.join(name), body);
    }
}
